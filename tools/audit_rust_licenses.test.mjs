/**
 * Unit tests for the license-audit tooling.
 *
 * Run:  node --test tools/audit_rust_licenses.test.mjs
 *
 * Scope: the PURE logic only — lockfile parsing, cache keys, summary
 * aggregation, concurrency helper, and HTTP retry behaviour against a fake
 * fetch. No test here touches the real network, so the suite is deterministic
 * and offline-safe. The end-to-end registry query is exercised by running the
 * CLI itself, not by this file.
 */

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, writeFile, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import {
  parseCargoLock,
  cacheKey,
  summarize,
  mapLimit,
  fetchLicense,
  runAudit,
} from './audit_rust_licenses.mjs';

/* ---------------------------------------------------------------- parsing */

test('parses a registry package with source and checksum', () => {
  const lock = [
    '# This file is automatically @generated by Cargo.',
    'version = 4',
    '',
    '[[package]]',
    'name = "serde"',
    'version = "1.0.229"',
    'source = "registry+https://github.com/rust-lang/crates.io-index"',
    'checksum = "deadbeef"',
    '',
  ].join('\n');

  assert.deepEqual(parseCargoLock(lock), [
    {
      name: 'serde',
      version: '1.0.229',
      source: 'registry+https://github.com/rust-lang/crates.io-index',
    },
  ]);
});

test('records a workspace member (no source) as null-source', () => {
  const lock = ['[[package]]', 'name = "handy"', 'version = "0.9.8"', ''].join('\n');
  assert.deepEqual(parseCargoLock(lock), [{ name: 'handy', version: '0.9.8', source: null }]);
});

test('parses a git-sourced dependency', () => {
  const lock = [
    '[[package]]',
    'name = "tao"',
    'version = "0.35.3"',
    'source = "git+https://github.com/cjpais/tao?rev=c3bee28c#c3bee28c1d446d95f08c95c3b6f8d4bde052b876"',
    '',
  ].join('\n');
  const [pkg] = parseCargoLock(lock);
  assert.equal(pkg.name, 'tao');
  assert.ok(pkg.source.startsWith('git+https://github.com/cjpais/tao'));
});

test('parses multiple packages and stops at the next table header', () => {
  const lock = [
    '[[package]]',
    'name = "a"',
    'version = "0.1.0"',
    'source = "registry+https://github.com/rust-lang/crates.io-index"',
    '',
    '[[package]]',
    'name = "b"',
    'version = "0.2.0"',
    'dependencies = [',
    ' "a",',
    ']',
    '',
  ].join('\n');

  const parsed = parseCargoLock(lock);
  assert.equal(parsed.length, 2);
  assert.deepEqual(
    parsed.map((p) => p.name),
    ['a', 'b'],
  );
  assert.equal(parsed[1].version, '0.2.0');
});

test('a package name containing a bracket-like sequence is not truncated', () => {
  const lock = ['[[package]]', 'name = "x[[y]]z"', 'version = "1.0.0"', ''].join('\n');
  assert.equal(parseCargoLock(lock)[0].name, 'x[[y]]z');
});

test('returns an empty array for a lockfile with no packages', () => {
  assert.deepEqual(parseCargoLock('# empty\nversion = 4\n'), []);
});

test('skips malformed package blocks that lack a version', () => {
  const lock = [
    '[[package]]',
    'name = "broken"',
    '',
    '[[package]]',
    'name = "ok"',
    'version = "1.0.0"',
    '',
  ].join('\n');
  assert.deepEqual(
    parseCargoLock(lock).map((p) => p.name),
    ['ok'],
  );
});

/* ------------------------------------------------------------ aggregation */

test('cache keys distinguish two versions of the same crate', () => {
  assert.notEqual(cacheKey('cpal', '0.16.0'), cacheKey('cpal', '0.17.0'));
  assert.equal(cacheKey('cpal', '0.16.0'), 'cpal@0.16.0');
});

test('summary counts a null license as an explicit undeclared bucket', () => {
  const summary = summarize([
    { license: 'MIT' },
    { license: 'MIT' },
    { license: 'Apache-2.0 OR MIT' },
    { license: null },
  ]);
  assert.equal(summary['MIT'], 2);
  assert.equal(summary['Apache-2.0 OR MIT'], 1);
  assert.equal(summary['<NO LICENSE DECLARED>'], 1);
});

test('summary of an empty set is empty, not undefined', () => {
  assert.deepEqual(summarize([]), {});
});

/* ---------------------------------------------------------- concurrency */

test('mapLimit preserves input order despite out-of-order completion', async () => {
  const items = [30, 5, 15, 1];
  const out = await mapLimit(items, 4, async (ms) => {
    await new Promise((r) => setTimeout(r, ms));
    return ms * 2;
  });
  assert.deepEqual(out, [60, 10, 30, 2]);
});

test('mapLimit never exceeds its concurrency ceiling', async () => {
  let active = 0;
  let peak = 0;
  await mapLimit(Array.from({ length: 20 }, (_, i) => i), 3, async () => {
    active++;
    peak = Math.max(peak, active);
    await new Promise((r) => setTimeout(r, 2));
    active--;
  });
  assert.ok(peak <= 3, `peak concurrency was ${peak}`);
});

test('mapLimit handles an empty input list', async () => {
  assert.deepEqual(await mapLimit([], 4, async () => 1), []);
});

/* ------------------------------------------------------------ HTTP retry */

const jsonResponse = (body, { status = 200, headers = {} } = {}) => ({
  ok: status >= 200 && status < 300,
  status,
  headers: { get: (k) => headers[k.toLowerCase()] ?? null },
  json: async () => body,
});

test('fetchLicense returns the SPDX expression on success', async () => {
  const r = await fetchLicense('tauri', '2.12.2', {
    fetchImpl: async () => jsonResponse({ version: { license: 'Apache-2.0 OR MIT' } }),
  });
  assert.equal(r.status, 'ok');
  assert.equal(r.license, 'Apache-2.0 OR MIT');
});

test('fetchLicense treats a 200 with no license field as undeclared, not a throttle', async () => {
  const r = await fetchLicense('somecrate', '1.0.0', {
    fetchImpl: async () => jsonResponse({ version: {} }),
  });
  assert.equal(r.status, 'ok');
  assert.equal(r.license, null);
});

test('fetchLicense maps 404 to not-found without retrying', async () => {
  let calls = 0;
  const r = await fetchLicense('ghost', '9.9.9', {
    fetchImpl: async () => {
      calls++;
      return jsonResponse({}, { status: 404 });
    },
  });
  assert.equal(r.status, 'not-found');
  assert.equal(calls, 1);
});

test('fetchLicense retries a 429 and succeeds (the rate-limit regression)', async () => {
  let calls = 0;
  const r = await fetchLicense('throttled', '1.0.0', {
    fetchImpl: async () => {
      calls++;
      if (calls < 3) return jsonResponse({}, { status: 429, headers: { 'retry-after': '0' } });
      return jsonResponse({ version: { license: 'MIT' } });
    },
  });
  assert.equal(calls, 3);
  assert.equal(r.status, 'ok');
  assert.equal(r.license, 'MIT');
});

test('fetchLicense reports rate-limited rather than a false "no license" when exhausted', async () => {
  const r = await fetchLicense('always-throttled', '1.0.0', {
    fetchImpl: async () => jsonResponse({}, { status: 429 }),
    sleepImpl: async () => {},
  });
  assert.equal(r.status, 'rate-limited');
  assert.equal(r.license, undefined);
});

test('fetchLicense retries network errors and reports them when persistent', async () => {
  let calls = 0;
  const r = await fetchLicense('flaky', '1.0.0', {
    fetchImpl: async () => {
      calls++;
      throw new Error('ECONNRESET');
    },
    sleepImpl: async () => {},
  });
  assert.ok(calls > 1, 'should have retried');
  assert.equal(r.status, 'network-error');
});

test('fetchLicense honours a Retry-After header when deciding how long to wait', async () => {
  const waits = [];
  let calls = 0;
  await fetchLicense('throttled', '1.0.0', {
    fetchImpl: async () => {
      calls++;
      if (calls === 1) return jsonResponse({}, { status: 429, headers: { 'retry-after': '7' } });
      return jsonResponse({ version: { license: 'MIT' } });
    },
    sleepImpl: async (ms) => waits.push(ms),
  });
  assert.deepEqual(waits, [7000]);
});

/* ------------------------------------------- runAudit end-to-end (offline) */

const LOCK = [
  '[[package]]',
  'name = "cached-crate"',
  'version = "1.0.0"',
  'source = "registry+https://github.com/rust-lang/crates.io-index"',
  '',
  '[[package]]',
  'name = "fresh-crate"',
  'version = "2.0.0"',
  'source = "registry+https://github.com/rust-lang/crates.io-index"',
  '',
  '[[package]]',
  'name = "git-crate"',
  'version = "3.0.0"',
  'source = "git+https://github.com/example/git-crate#abc123"',
  '',
].join('\n');

test('runAudit merges a populated cache without losing names (regression: cache-hit sort crash)', async (t) => {
  const dir = await mkdtemp(join(tmpdir(), 'licaudit-'));
  t.after(() => rm(dir, { recursive: true, force: true }));

  const lockPath = join(dir, 'Cargo.lock');
  const outPath = join(dir, 'out.json');
  const cachePath = join(dir, 'cache.json');
  await writeFile(lockPath, LOCK, 'utf8');

  // A cache record deliberately carries NO name/version — exactly the shape
  // that used to crash the merge sort with "undefined.localeCompare".
  await writeFile(
    cachePath,
    JSON.stringify({
      'cached-crate@1.0.0': { status: 'ok', license: 'MIT', repository: 'https://example.com/c' },
    }),
    'utf8',
  );

  let fetchCalls = 0;
  const out = await runAudit({
    lockPath,
    outPath,
    cachePath,
    concurrency: 2,
    log: () => {},
    fetchImpl: async (url) => {
      fetchCalls++;
      assert.match(url, /fresh-crate\/2\.0\.0/, 'must only fetch the uncached crate');
      return jsonResponse({ version: { license: 'Apache-2.0' } });
    },
  });

  assert.equal(fetchCalls, 1, 'cached crate must not be re-fetched');
  assert.equal(out.cache_hits, 1);
  assert.deepEqual(
    out.packages.map((p) => [p.name, p.version, p.license]),
    [
      ['cached-crate', '1.0.0', 'MIT'],
      ['fresh-crate', '2.0.0', 'Apache-2.0'],
    ],
  );
  // Git-sourced packages are reported separately and never queried.
  assert.deepEqual(
    out.git_and_path_packages.map((p) => p.name),
    ['git-crate'],
  );
  assert.equal(out.unresolved.length, 0);
  assert.deepEqual(out.license_summary, { MIT: 1, 'Apache-2.0': 1 });

  // The report must be on disk and parseable.
  assert.deepEqual(JSON.parse(await readFile(outPath, 'utf8')).packages.length, 2);
});

test('runAudit records a throttled dependency as unresolved, never as "no license"', async (t) => {
  const dir = await mkdtemp(join(tmpdir(), 'licaudit-'));
  t.after(() => rm(dir, { recursive: true, force: true }));

  const lockPath = join(dir, 'Cargo.lock');
  const outPath = join(dir, 'out.json');
  await writeFile(lockPath, LOCK, 'utf8');

  const out = await runAudit({
    lockPath,
    outPath,
    cachePath: join(dir, 'nonexistent-cache.json'),
    concurrency: 2,
    log: () => {},
    fetchImpl: async () => jsonResponse({}, { status: 429 }),
  });

  const names = out.unresolved.map((u) => u.name).sort();
  assert.deepEqual(names, ['cached-crate', 'fresh-crate']);
  assert.ok(out.unresolved.every((u) => u.status === 'rate-limited'));
  assert.equal(out.unresolved_count, 2);
  // Crucially: NOT counted as an undeclared license, and not counted at all.
  assert.deepEqual(out.license_summary, {});
  assert.ok(
    out.packages.every((p) => p.resolved === false),
    'throttled packages must be marked unresolved in the package list',
  );
});

test('runAudit treats a 200 with no license field as undeclared', async (t) => {
  const dir = await mkdtemp(join(tmpdir(), 'licaudit-'));
  t.after(() => rm(dir, { recursive: true, force: true }));

  const lockPath = join(dir, 'Cargo.lock');
  await writeFile(lockPath, LOCK, 'utf8');

  const out = await runAudit({
    lockPath,
    outPath: join(dir, 'out.json'),
    cachePath: join(dir, 'nonexistent-cache.json'),
    concurrency: 2,
    log: () => {},
    fetchImpl: async () => jsonResponse({ version: {} }),
  });

  assert.equal(out.unresolved.length, 0);
  assert.equal(out.license_summary['<NO LICENSE DECLARED>'], 2);
});
